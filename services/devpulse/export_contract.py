"""Export schemas without connecting to infrastructure or loading developer secrets.

The small generator accepts the JSON Schema subset used by these Pydantic DTOs;
unknown constructs fail rather than silently weakening client types.
"""

import json
from pathlib import Path

from app.core.config import Settings
from app.main import create_app


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "anyOf" in schema:
        return " | ".join(ts(item) for item in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind is None and set(schema) <= {"title", "description", "default"}:
        return "unknown"
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind in {"number", "integer"}:
        return "number"
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind == "object":
        if not schema.get("properties"):
            return "Record<string, unknown>"
        fields = []
        for key, value in schema.get("properties", {}).items():
            optional = "" if key in schema.get("required", []) else "?"
            fields.append(f"  {key}{optional}: {ts(value)};")
        return "{\n" + "\n".join(fields) + "\n}"
    raise ValueError(f"Unsupported schema: {schema}")


if __name__ == "__main__":
    settings = Settings(
        _env_file=None,
        environment="test",
        database_url="postgresql+psycopg://unused@127.0.0.1/unused",
        redis_url="redis://127.0.0.1:6380/15",
    )
    schema = create_app(settings).openapi()
    Path("openapi.json").write_text(json.dumps(schema, indent=2) + "\n", encoding="utf-8")
    types = "// Generated by services/devpulse/export_contract.py. Do not edit.\n"
    for name, definition in schema["components"]["schemas"].items():
        types += f"export type {name} = {ts(definition)};\n"
    target = Path("../../src/features/devpulse/api/contracts.ts")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(types, encoding="utf-8")
